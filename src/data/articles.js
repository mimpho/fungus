// ─── Helper de localización ────────────────────────────────────────────────────
export function getLocalizedArticle(article, lang) {
  if (!lang || lang === 'es') return article
  return {
    ...article,
    title:    article[`title_${lang}`]    ?? article.title,
    subtitle: article[`subtitle_${lang}`] ?? article.subtitle,
    summary:  article[`summary_${lang}`]  ?? article.summary,
    tags:     article[`tags_${lang}`]     ?? article.tags,
  }
}
